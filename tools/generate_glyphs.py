#!/usr/bin/env python3
"""Convert the Bongo Cat OTF font into Cairo path data for the GNOME extension.

The original DMS widget renders the "classic" cat as text with a custom font:
each pose is two glyphs drawn side by side ("bc", "dc", ...). Loading a private
font file inside GNOME Shell is not reliably possible, so instead we extract the
glyph outlines once, at build time, and draw them with Cairo at runtime.

Usage:  python3 tools/generate_glyphs.py assets/bongocat-Regular.otf lib/catGlyphs.js
Requires: fontTools  (pip install fonttools)
"""
import json
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

# Same glyph pairs as BongoWidget.qml (glyphMap / blinkGlyph / sleepGlyph).
POSES = {
    "idle": "bc",
    "left": "dc",
    "right": "ba",
    "both": "da",
    "blink": "gh",
    "sleep": "ef",
}
# DMS uses letterSpacing = -0.05 * pixelSize between the two halves.
LETTER_SPACING_EM = -0.05


class CairoPen(BasePen):
    """Records outlines as compact Cairo commands (y axis flipped)."""

    def __init__(self, glyph_set, dx):
        super().__init__(glyph_set)
        self.cmds = []
        self.dx = dx

    def _p(self, pt):
        return [round(pt[0] + self.dx, 1), round(-pt[1], 1)]

    def _moveTo(self, pt):
        self.cmds.append(["M", *self._p(pt)])

    def _lineTo(self, pt):
        self.cmds.append(["L", *self._p(pt)])

    def _curveToOne(self, p1, p2, p3):
        self.cmds.append(["C", *self._p(p1), *self._p(p2), *self._p(p3)])

    def _closePath(self):
        self.cmds.append(["Z"])

    _endPath = _closePath


def main(src, dst):
    font = TTFont(src)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm

    poses = {}
    for pose, text in POSES.items():
        cmds, x = [], 0.0
        for ch in text:
            name = cmap[ord(ch)]
            pen = CairoPen(glyph_set, x)
            glyph_set[name].draw(pen)
            cmds += pen.cmds
            x += glyph_set[name].width + LETTER_SPACING_EM * upm
        poses[pose] = cmds

    # Union bounding box over all poses -> one fixed frame, so the body never
    # jumps between poses (same goal as the fixed offsets in BongoCatView.qml).
    xs, ys = [], []
    for cmds in poses.values():
        for c in cmds:
            xs += c[1::2]
            ys += c[2::2]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)

    def norm(cmds):
        out = []
        for c in cmds:
            pts = [round(v - (minx if i % 2 == 0 else miny), 1) for i, v in enumerate(c[1:])]
            out.append([c[0], *pts])
        return out

    data = {
        "width": round(maxx - minx, 1),
        "height": round(maxy - miny, 1),
        "poses": {k: norm(v) for k, v in poses.items()},
    }
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/generate_glyphs.py from assets/bongocat-Regular.otf.\n")
        f.write("// Do not edit by hand.\n")
        f.write("export const GLYPHS = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
